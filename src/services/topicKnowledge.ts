import type { ScriptDomainId } from './scriptDomains';

/**
 * 실전 지식 팩.
 *
 * 도메인 문장 은행만으로는 "전세사기"에 등기부등본 을구 이야기를 할 수 없다.
 * 도메인은 말투를 정하고, 이 팩은 **그 주제에서 실제로 확인해야 하는 것**을
 * 정한다. 각 단계는 카메라 앞에서 그대로 말할 수 있는 문장이고, 근거는
 * `basis`에 남긴다(콘솔이 "왜 이 대본인지" 보여줄 때 쓴다).
 *
 * 수치·기한은 제도가 바뀌면 틀린 정보가 되므로, 변동되는 값은 단정하지 않고
 * "이번 차수 공고에서 확인"으로 남긴다. 확인되지 않은 숫자를 말하는 것이
 * 숏폼 정보형 콘텐츠에서 가장 큰 위험이다.
 */
export interface KnowledgePack {
  id: string;
  domain: ScriptDomainId;
  /** 팩 이름(콘솔 표시용). */
  label: string;
  /** 훅·문제에서 부르는 이름. 분류기가 만든 이름보다 정확할 때 덮어쓴다. */
  subject: string;
  /** 단서와 무게. 두 단어가 같이 나오면 점수가 더해진다. */
  cues: Array<[RegExp, number]>;
  problems: string[];
  steps: string[];
  /** 앵글별 훅. 없으면 도메인 은행의 훅을 쓴다. */
  hooks?: Partial<Record<'problem-solve' | 'numbers' | 'checklist' | 'before-after' | 'contrarian', string[]>>;
  screens?: { step: string[]; hook?: string[]; problem?: string[] };
  tags?: string[];
  /** 이 단계들의 근거(제도·절차). 콘솔과 테스트가 함께 읽는다. */
  basis: string;
}

