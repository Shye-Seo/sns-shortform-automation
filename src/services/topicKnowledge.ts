export interface KnowledgeMatch {
  pack: KnowledgePack;
  score: number;
  matched: string[];
}

/**
 * 주제에 걸린 지식 팩을 점수순으로 돌려준다.
 *
 * 같은 단어가 여러 팩에 걸릴 수 있으므로(월세 → 월세 계약 / 청년 월세 지원금)
 * 단어마다 무게를 다르게 주고, 점수가 같으면 긴 단어가 이긴다.
 */
export function matchKnowledgePacks(topic: string): KnowledgeMatch[] {
  const matches: KnowledgeMatch[] = [];
  for (const pack of KNOWLEDGE_PACKS) {
    let score = 0;
    const matched: string[] = [];
    for (const [pattern, weight] of pack.cues) {
      const found = topic.match(new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`));
      if (!found) continue;
      const unique = Array.from(new Set(found.map((value) => value.replace(/\s+/g, ''))));
      score += weight * Math.min(2, unique.length);
      matched.push(...unique);
    }
    if (score > 0) matches.push({ pack, score, matched });
  }
  return matches.sort(
    (a, b) =>
      b.score - a.score ||
      Math.max(...b.matched.map((m) => m.length)) - Math.max(...a.matched.map((m) => m.length)) ||
      a.pack.id.localeCompare(b.pack.id),
  );
}

/** 분류된 도메인 안에서 가장 잘 맞는 팩. */
export function resolveKnowledge(topic: string, domain: ScriptDomainId): KnowledgeMatch | null {
  return matchKnowledgePacks(topic).find((match) => match.pack.domain === domain) ?? null;
}
