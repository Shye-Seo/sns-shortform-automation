/**
 * 주제 도메인과 도메인별 문장 은행.
 *
 * 이 파일이 생긴 이유(2026-11-21 피드백):
 *   "퇴사한 30대 개발자의 일상"을 넣었더니 "길게 쓰기부터 버리세요",
 *   "제목과 첫 문장만 다시 씁니다"가 나왔다. 분류기가 '개발'만 보고 커리어(문서)
 *   카테고리를 골랐고, 그 카테고리의 문장 은행이 글쓰기 조언이었기 때문이다.
 *
 * 고친 방식:
 *   1) 분류는 하나의 정규식 목록이 아니라 **도메인별 가중치 + 장르 어미 보정**으로 한다.
 *      "…의 일상", "…브이로그"처럼 끝이 장르를 말하면 그 장르가 이긴다.
 *      "퇴사한 30대 개발자"의 퇴사·개발자는 소재일 뿐, 영상의 형식은 일상 기록이다.
 *   2) 도메인마다 4비트(훅·문제·해결·유도) 문장을 따로 쓴다. 문장은 그 도메인에서
 *      실제로 하는 말이어야 하고, 주제어를 문장마다 기계적으로 끼워 넣지 않는다.
 *      주제어는 훅에서 한 번, 문제에서 한 번만 자연스럽게 등장한다.
 *   3) 훅은 앵글(문제해결·숫자·체크리스트·전후·반전)별로 따로 쓴다. "이 순서만
 *      지키세요" 같은 범용 문장을 여행·카페에 붙이지 않는다.
 *
 * 문장 슬롯
 *   {n}   주제의 짧은 이름("개발자의 일상", "제주 2박3일")
 *   {n은}/{n이}/{n을}/{n과}/{n로}  조사가 붙은 형태
 *   {p}   장소("제주", "전포")
 *   {d}   도메인의 핵심 변수("하루의 순서", "이동 동선")
 */

